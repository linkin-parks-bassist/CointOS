def schema(kind):
    if 'InputFile' in kind:
        return {'anyOf': [{'type': 'string'}, {'type': 'object', 'properties': {'path': {'type': 'string'}},
                                            'required': ['path'], 'additionalProperties': False}]}
    if kind.startswith('Array of '):
        return {'type': 'array', 'items': schema(kind[9:])}
    if ' or ' in kind:
        return {'anyOf': [schema(part) for part in kind.split(' or ')]}
    return {'type': {'String': 'string', 'Integer': 'integer', 'Float': 'number',
                     'Boolean': 'boolean', 'True': 'boolean'}.get(kind, 'object')}


def declaration(method):
    fields = METHODS[method]
    properties = {name: {**schema(field['type']), 'description': field['type']}
                  for name, field in fields.items()}
    required = [name for name, field in fields.items() if field['required'] and name not in ('chat_id', 'user_id')]
    return {'type': 'function', 'function': {'name': PREFIX + method,
        'description': (re.sub(r'([A-Z])', r' \1', method).capitalize() + '. Bot API parameters; chat_id defaults to this chat and user_id to this user. '
                        'Upload files using {"path":"/absolute/file"}, including nested media. '
                        'Use telegram_tools for nested type fields. Requires user authority for the effect.'),
        'parameters': {'type': 'object', 'properties': properties, 'required': required, 'additionalProperties': False}}}


