def discover(arguments):
    if arguments.get('type_name'):
        name = arguments['type_name']
        if name not in CATALOG['types']:
            raise ValueError('Unknown Telegram type')
        return {'ok': True, 'type': name, 'fields': CATALOG['types'][name]}, []
    names = arguments.get('names')
    if names is None:
        query = arguments.get('query', '').lower().removeprefix(PREFIX)
        query = {'image': 'photo', 'images': 'photo', 'picture': 'photo', 'file': 'document',
                 'album': 'mediagroup', 'button': 'replymarkup', 'typing': 'chataction',
                 'payment': 'invoice', 'download': 'getfile'}.get(query, query)
        names = [name for name in METHODS if query in name.lower()] if query else []
    names = [name.removeprefix(PREFIX) for name in names]
    if any(name not in METHODS for name in names):
        raise ValueError('Unknown or service-owned Telegram method')
    return {'ok': True, 'methods': names or list(METHODS),
            'callable_tools': [PREFIX + name for name in names],
            'next': 'Call the listed telegram_ functions directly. They are attached to your next request; do not use mcp_call for them.' if names else 'Select names or a query to expose callable tools.',
            'signatures': {name: METHODS[name] for name in names},
            'source': CATALOG['source'], 'service_owned': CATALOG['excluded']}, [declaration(name) for name in names]


def request(token, method, parameters, timeout):
    """Upload explicit file objects without buffering large files in memory; never retry effects."""
    files = []

    def convert(value):
        if isinstance(value, dict):
            if set(value) == {'path'}:
                path = Path(value['path']).expanduser()
                if not path.is_absolute() or not path.is_file():
                    raise ValueError('Telegram upload needs an absolute regular-file path')
                name = 'upload' + str(len(files))
                files.append((name, path))
                return 'attach://' + name
            return {key: convert(item) for key, item in value.items()}
        if isinstance(value, list):
            return [convert(item) for item in value]
        return value

    parameters = convert(parameters)
    url = f'https://api.telegram.org/bot{token}/{method}'
    try:
        with tempfile.SpooledTemporaryFile(max_size=1024 * 1024) as body:
            if files:
                boundary = uuid.uuid4().hex
                for name, value in parameters.items():
                    encoded = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
                    body.write(f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"\r\n\r\n{encoded}\r\n'.encode())
                for name, path in files:
                    # Preserve document names while refusing multipart header injection.
                    filename = re.sub(r'[\r\n"\\]', '_', path.name)
                    mime = mimetypes.guess_type(path.name)[0] or 'application/octet-stream'
                    body.write(f'--{boundary}\r\nContent-Disposition: form-data; name="{name}"; filename="{filename}"\r\nContent-Type: {mime}\r\n\r\n'.encode())
                    with path.open('rb') as source:
                        import shutil
                        shutil.copyfileobj(source, body)
                    body.write(b'\r\n')
                body.write(f'--{boundary}--\r\n'.encode())
                content_type = 'multipart/form-data; boundary=' + boundary
            else:
                body.write(json.dumps(parameters).encode())
                content_type = 'application/json'
            length = body.tell()
            body.seek(0)
            req = urllib.request.Request(url, body, {'Content-Type': content_type, 'Content-Length': str(length)})
            with urllib.request.urlopen(req, timeout=timeout) as response:
                result = json.load(response)
    except urllib.error.HTTPError as error:
        try:
            result = json.load(error)
        except (ValueError, OSError):
            result = {'description': f'HTTP {error.code}'}
        return {'ok': False, 'error': str(result.get('description', 'Telegram refused request')).replace(token, '[redacted]'),
                'error_code': error.code, 'parameters': redact(result.get('parameters', {}), token)}
    except (OSError, ValueError):
        return {'ok': False, 'error': 'Telegram transport failed; acceptance is unknown. Inspect before repeating an effect.'}
    if not result.get('ok'):
        return {'ok': False, 'error': str(result.get('description', 'Telegram refused request')).replace(token, '[redacted]'),
                'parameters': redact(result.get('parameters', {}), token)}
    return {'ok': True, 'result': redact(result.get('result'), token)}


def redact(value, token):
    if isinstance(value, str):
        return re.sub(r'\b[0-9]{6,}:[A-Za-z0-9_-]{20,}\b', '[redacted]', value.replace(token, '[redacted]'))
    if isinstance(value, list):
        return [redact(item, token) for item in value]
    if isinstance(value, dict):
        return {key: '[redacted]' if 'token' in key.lower() else redact(item, token) for key, item in value.items()}
    return value


def prepare(name, arguments, user, chat):
    method = name.removeprefix(PREFIX)
    if method not in METHODS:
        raise ValueError('Unknown or service-owned Telegram method')
    fields = METHODS[method]
    if set(arguments) - fields.keys():
        raise ValueError('Unknown Telegram parameter(s): ' + ', '.join(sorted(set(arguments) - fields.keys())))
    parameters = dict(arguments)
    for key, default in (('chat_id', chat), ('user_id', user)):
        if key in fields and not (key == 'chat_id' and parameters.get('inline_message_id')):
            parameters.setdefault(key, default)
    missing = [key for key, field in fields.items() if field['required'] and key not in parameters]
    if missing:
        raise ValueError('Missing Telegram parameter(s): ' + ', '.join(missing))
    return method, parameters


def is_delivery(method):
    return method.startswith(('send', 'copyMessage', 'forwardMessage')) and method not in (
        'sendChatAction', 'sendMessageDraft', 'sendRichMessageDraft')


def event(entry):
    """Read only service-framed event metadata, leaving ordinary user text alone."""
    text = entry.get('text', '')
    for tag, kind in (('cointos-telegram-callback', 'callback_query'), ('cointos-telegram-event', None)):
        prefix, suffix = '<' + tag + '>', '</' + tag + '>'
        if text.startswith(prefix) and text.endswith(suffix):
            try:
                value = json.loads(text[len(prefix):-len(suffix)])
                return (kind, value) if kind else (value['kind'], value['event'])
            except (ValueError, KeyError, TypeError):
                break
    return None, {}


ANSWERS = {'callback_query': ('answerCallbackQuery', 'callback_query_id'),
           'inline_query': ('answerInlineQuery', 'inline_query_id'),
           'shipping_query': ('answerShippingQuery', 'shipping_query_id'),
           'pre_checkout_query': ('answerPreCheckoutQuery', 'pre_checkout_query_id')}


def expects_reply(entry):
    kind, _ = event(entry)
    return kind is None or kind in ANSWERS


def answers(name, arguments, entry):
    kind, data = event(entry)
    method, parameter = ANSWERS.get(kind, (None, None))
    return name == PREFIX + str(method) and arguments.get(parameter) == data.get('id')
